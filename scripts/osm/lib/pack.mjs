/** Packing for the generated modules: typed arrays as base64 strings, and the shared file header. */
import fs from "node:fs";

export const b64 = (typed) => Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString("base64");
/** World coordinates as int16 tenths of a unit (±3276 units covers the near world and the far ends). */
export const q10 = (v) => Math.max(-32768, Math.min(32767, Math.round(v * 10)));
export const r1 = (v) => Math.round(v * 10) / 10;

export const header = (what, script, sources) =>
  `/**\n * ${what}\n * Generated by ${script} from ${sources}; do not edit by hand.\n */\n`;

export function writeModule(file, text) {
  fs.writeFileSync(file, text);
  console.log(`wrote ${file.replace(/\\/g, "/").split("/my_portfolio/")[1] ?? file} (${(text.length / 1024).toFixed(1)} KB)`);
}
